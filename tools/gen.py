def col_sql(c):
    s = f"{c.name} {SQL_TYPES[c.ty]}"
    if c.gen:
        s += f" GENERATED ALWAYS AS ({c.gen}) STORED"
    if c.not_null:
        s += " NOT NULL"
    if c.default is not None:
        s += f" DEFAULT {c.default}"
    if c.unique:
        s += " UNIQUE"
    if c.enum:
        s += f" CHECK ({c.name} IN ({', '.join(repr(e) for e in c.enum)}))"
    if c.check:
        s += f" CHECK ({c.check})"
    if c.fk:
        restrict = c.fk.endswith("!")
        tbl = c.fk.rstrip("!")
        action = "RESTRICT" if restrict else ("CASCADE" if c.req else "SET NULL")
        s += f" REFERENCES {tbl}(id) ON DELETE {action}"
    return s


def gen_sql():
    out = ["-- GENERATED by tools/gen.py - do not edit by hand", SQL_PRE]
    for seq in SEQUENCES:
        out.append(f"CREATE SEQUENCE IF NOT EXISTS {seq};")
    for t in TABLES:
        if t.since > 1:
            continue
        lines = ["id uuid PRIMARY KEY DEFAULT gen_random_uuid()"] + [col_sql(c) for c in t.cols if c.since == 1]
        lines += ["created_at timestamptz NOT NULL DEFAULT now()", "updated_at timestamptz NOT NULL DEFAULT now()"]
        for u in t.uniques:
            lines.append(f"UNIQUE ({', '.join(u)})")
        for ch in t.checks:
            lines.append(f"CHECK ({ch})")
        out.append(f"CREATE TABLE IF NOT EXISTS {t.name} (\n  " + ",\n  ".join(lines) + "\n);")
        for c in t.cols:
            if c.since == 1 and (c.fk or c.name in ("status", "stage")):
                out.append(f"CREATE INDEX IF NOT EXISTS idx_{t.name}_{c.name} ON {t.name}({c.name});")
        out.append(f"DROP TRIGGER IF EXISTS trg_{t.name}_updated ON {t.name};")
        out.append(f"CREATE TRIGGER trg_{t.name}_updated BEFORE UPDATE ON {t.name} FOR EACH ROW EXECUTE FUNCTION set_updated_at();")
    # set_updated_at must exist before triggers: prepend
    fn = ("CREATE OR REPLACE FUNCTION set_updated_at() RETURNS trigger AS $$\n"
          "BEGIN NEW.updated_at = now(); RETURN NEW; END $$ LANGUAGE plpgsql;")
    out.insert(2, fn)
    out.append("CREATE INDEX IF NOT EXISTS idx_am_readings_series ON am_meter_readings(asset_id, metric, recorded_at DESC);")
    out.append("CREATE INDEX IF NOT EXISTS idx_ehs_env_metric ON ehs_environmental_readings(site, metric, reading_date);")
    out.append(SQL_POST)
    open(f"{ROOT}/migrations/001_schema.sql", "w").write("\n".join(out))
    gen_upgrades()


def gen_upgrades():
    titles = {2: ("002_pm_portfolio", "project portfolio attributes + import batches"),
              3: ("003_crm_datasets", "CRM sales pipeline, customers, orders, import quarantine, models"),
              4: ("007_erp_integration", "links between suite modules and the ERP core (finance/HR), finance+hr roles")}
    for ver, (fname, title) in titles.items():
        out = ["-- GENERATED by tools/gen.py - do not edit by hand", f"-- Upgrade {ver:03d}: {title}"]
        for t in TABLES:                       # new tables first so ALTERs below can reference them
            if t.since == ver:
                lines = ["id uuid PRIMARY KEY DEFAULT gen_random_uuid()"] + [col_sql(c) for c in t.cols]
                lines += ["created_at timestamptz NOT NULL DEFAULT now()", "updated_at timestamptz NOT NULL DEFAULT now()"]
                for u in t.uniques:
                    lines.append(f"UNIQUE ({', '.join(u)})")
                for ch in t.checks:
                    lines.append(f"CHECK ({ch})")
                out.append(f"CREATE TABLE IF NOT EXISTS {t.name} (\n  " + ",\n  ".join(lines) + "\n);")
                for c in t.cols:
                    if c.fk or c.name in ("status", "kind"):
                        out.append(f"CREATE INDEX IF NOT EXISTS idx_{t.name}_{c.name} ON {t.name}({c.name});")
                out.append(f"DROP TRIGGER IF EXISTS trg_{t.name}_updated ON {t.name};")
                out.append(f"CREATE TRIGGER trg_{t.name}_updated BEFORE UPDATE ON {t.name} FOR EACH ROW EXECUTE FUNCTION set_updated_at();")
        for t in TABLES:
            if t.since < ver:
                for c in t.cols:
                    if c.since == ver:
                        out.append(f"ALTER TABLE {t.name} ADD COLUMN IF NOT EXISTS {col_sql(c)};")
                        if c.fk or c.name in ("project_type", "region", "department", "complexity", "close_date", "engage_date"):
                            out.append(f"CREATE INDEX IF NOT EXISTS idx_{t.name}_{c.name} ON {t.name}({c.name});")
        if ver == 2:
            out.append("CREATE INDEX IF NOT EXISTS idx_pm_projects_start ON pm_projects(start_date);")
        out.append(EXTRA_UPGRADE_SQL.get(ver, ""))
        if ver == 3:
            out.append("CREATE INDEX IF NOT EXISTS idx_crm_orders_customer ON crm_orders(customer_id);")
            out.append("CREATE INDEX IF NOT EXISTS idx_crm_customers_email ON crm_customers(lower(email));")
            out.append("CREATE INDEX IF NOT EXISTS idx_crm_customers_kind_last ON crm_customers(kind, last_activity_date);")
        open(f"{ROOT}/migrations/{fname}.sql", "w").write("\n".join(out) + "\n")


PARSE = {"u": "parse_uuid", "i": "parse_i32", "bi": "parse_i64", "f": "parse_f64", "d": "parse_dec",
         "b": "parse_bool", "dt": "parse_date", "ts": "parse_ts"}


def gen_entity(t):
    L = ["// GENERATED by tools/gen.py - do not edit by hand",
         "use crate::crud::*;", "use crate::error::AppResult;", "use sea_orm::entity::prelude::*;",
         "use serde::{Deserialize, Serialize};", "use std::collections::HashMap;", "",
         "#[derive(Clone, Debug, Default, PartialEq, DeriveEntityModel, Serialize, Deserialize)]",
         "#[serde(default)]",
         f'#[sea_orm(table_name = "{t.name}")]', "pub struct Model {",
         "    #[sea_orm(primary_key, auto_increment = false)]", "    pub id: Uuid,"]
    for c in t.cols:
        rt = RUST_TYPES[c.ty]
        rt = rt if (c.not_null or (c.gen and c.req)) else f"Option<{rt}>"
        if c.hidden:
            L.append("    #[serde(skip_serializing)]")
        L.append(f"    pub {c.name}: {rt},")
    L += ["    pub created_at: DateTimeWithTimeZone,", "    pub updated_at: DateTimeWithTimeZone,", "}", "",
          "#[derive(Copy, Clone, Debug, EnumIter, DeriveRelation)]", "pub enum Relation {}", "",
          "impl ActiveModelBehavior for ActiveModel {}", ""]
    ro = ["id", "created_at", "updated_at"] + [c.name for c in t.cols if c.gen or c.hidden]
    L.append("#[allow(dead_code)]")
    L.append(f"pub const READ_ONLY: &[&str] = &[{', '.join(chr(34) + r + chr(34) for r in ro)}];")
    L.append("")
    L.append("#[allow(dead_code)]")
    L.append("pub fn apply_filters(mut q: Select<Entity>, p: &HashMap<String, String>) -> AppResult<Select<Entity>> {")
    cols = [("id", "u")] + [(c.name, c.ty) for c in t.cols if not c.hidden] + [("created_at", "ts"), ("updated_at", "ts")]
    for n, ty in cols:
        camel = "".join(w.capitalize() for w in n.split("_"))
        if ty == "j":
            continue
        if ty == "s":
            L.append(f'    if let Some(v) = p.get("{n}") {{ q = q.filter(Column::{camel}.eq(v.clone())); }}')
        else:
            f = PARSE[ty]
            L.append(f'    if let Some(v) = p.get("{n}") {{ q = q.filter(Column::{camel}.eq({f}("{n}", v)?)); }}')
        if ty in ("i", "bi", "f", "d", "dt", "ts"):
            f = PARSE[ty]
            L.append(f'    if let Some(v) = p.get("{n}_gte") {{ q = q.filter(Column::{camel}.gte({f}("{n}_gte", v)?)); }}')
            L.append(f'    if let Some(v) = p.get("{n}_lte") {{ q = q.filter(Column::{camel}.lte({f}("{n}_lte", v)?)); }}')
    L += ["    Ok(q)", "}", ""]
    open(f"{ROOT}/src/entities/{t.name}.rs", "w").write("\n".join(L))


def gen_mod_and_routes():
    m = ["// GENERATED by tools/gen.py - do not edit by hand"] + [f"pub mod {t.name};" for t in TABLES]
    open(f"{ROOT}/src/entities/mod.rs", "w").write("\n".join(m) + "\n")
    R = ["// GENERATED by tools/gen.py - do not edit by hand",
         "use crate::state::AppState;", "use axum::Router;", "",
         "pub fn router() -> Router<AppState> {", "    Router::new()"]
    for t in TABLES:
        if not t.ops:
            continue
        mod = API_MODULE.get(t.module, t.module)
        R.append(f'        .nest("/api/{mod}/{t.resource}", crud_router!({t.name}, "{t.ops}"))')
    R.append("}")
    open(f"{ROOT}/src/routes_generated.rs", "w").write("\n".join(R) + "\n")
    # README table
    rows = ["| Module | Resource | Operations |", "|---|---|---|"]
    names = {"l": "list", "g": "get", "c": "create", "u": "update", "d": "delete"}
    for t in TABLES:
        if t.ops:
            mod = API_MODULE.get(t.module, t.module)
            rows.append(f"| {mod} | `/api/{mod}/{t.resource}` | {', '.join(names[o] for o in t.ops)} |")
    open(f"{ROOT}/CRUD_ENDPOINTS.md", "w").write("# Generated CRUD endpoints\n\n" + "\n".join(rows) + "\n")


def gen_frontend_schema():
    """Resource metadata for the Yew frontend (frontend/src/schema_generated.rs)."""
    def q(x):
        return '"' + str(x).replace("\\", "\\\\").replace('"', '\\"') + '"'
    L = ["// GENERATED by tools/gen.py - do not edit by hand",
         "use crate::schema::{ColDef, ResDef};", "", "pub static RESOURCES: &[ResDef] = &["]
    for t in TABLES:
        if not t.ops:
            continue
        mod = API_MODULE.get(t.module, t.module)
        L.append(f"    ResDef {{ module: {q(mod)}, slug: {q(t.resource)}, table: {q(t.name)}, ops: {q(t.ops)}, cols: &[")
        for c in t.cols:
            if c.hidden:
                continue
            enum = "&[" + ", ".join(q(e) for e in (c.enum or [])) + "]"
            req = "true" if (c.req and c.default is None and not c.gen) else "false"
            ro = "true" if c.gen else "false"
            L.append(f"        ColDef {{ name: {q(c.name)}, ty: {q(c.ty)}, req: {req}, readonly: {ro}, choices: {enum}, fk: {q(c.fk or '')} }},")
        L.append("    ] },")
    L.append("];")
    import os
    os.makedirs(f"{ROOT}/frontend/src", exist_ok=True)
    open(f"{ROOT}/frontend/src/schema_generated.rs", "w").write("\n".join(L) + "\n")


